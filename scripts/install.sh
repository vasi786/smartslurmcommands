#!/usr/bin/env bash
# install.sh — user-space install (no sudo)
# Usage:
#   ./scripts/install.sh                     # installs to ~/.local
#   ./scripts/install.sh /custom/prefix /custom/config_prefix      # e.g., /home/user/.local-alt /home/user/.config-alt

set -Eeuo pipefail
IFS=$'\n\t'

# ---------- Config: default to ~/.local ----------
DEFAULT_PREFIX="${HOME}/.local"
DEFAULT_CONFIG_PREFIX="${HOME}/.config"
PREFIX="${1:-$DEFAULT_PREFIX}"
CONFIG_PREFIX="${2:-$DEFAULT_CONFIG_PREFIX}"
BIN_DIR="${PREFIX}/bin"
SHARE_PARENT="${PREFIX}/share"
SHARE_DIR="${PREFIX}/share/smartslurmcommands"
MAN_DIR="${PREFIX}/share/man/man1"
USER_CONFIG_DIR="${CONFIG_PREFIX}/smartslurmcommands"
USER_CONFIG_FILE="$USER_CONFIG_DIR/config"

# ---------- Resolve repo root ----------
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"

# Build the replacement shared tree beside the live tree, then rename it into
# place. If anything fails after the swap, the EXIT trap restores the previous
# shared tree.
STAGE_DIR=""
BACKUP_DIR=""
SHARE_SWAPPED=false
INSTALL_COMPLETE=false

_install_cleanup() {
  local rc=$?
  trap - EXIT

  if ! $INSTALL_COMPLETE; then
    if [[ -n "$STAGE_DIR" && -d "$STAGE_DIR" ]]; then
      rm -rf -- "$STAGE_DIR"
    fi
    if $SHARE_SWAPPED; then
      rm -rf -- "$SHARE_DIR"
    fi
    if [[ -n "$BACKUP_DIR" && -d "$BACKUP_DIR" ]]; then
      mv "$BACKUP_DIR" "$SHARE_DIR"
    fi
  fi

  exit "$rc"
}
trap _install_cleanup EXIT

echo "==> Installing smartslurmcommands (user mode)"
echo "    PREFIX   : $PREFIX"
echo "    BIN_DIR  : $BIN_DIR"
echo "    SHARE_DIR: $SHARE_DIR"
echo "    MAN_DIR  : $MAN_DIR"
echo

# ---------- Create dirs ----------
mkdir -p "$BIN_DIR" "$SHARE_PARENT" "$MAN_DIR" "$USER_CONFIG_DIR"

# ---------- Create config file --------------
if [[ ! -f "$USER_CONFIG_FILE" ]]; then
  cp "${ROOT}"/config "$USER_CONFIG_FILE"
  echo "==>  Created $USER_CONFIG_FILE"
  echo ""
else
  echo "==>   Found existing $USER_CONFIG_FILE (left untouched)"
  echo ""
fi

# ---------- Build shared assets in a staging directory ----------
echo "==> Staging shared assets"
STAGE_DIR="$(mktemp -d "$SHARE_PARENT/.smartslurmcommands.new.XXXXXX")"
for d in lib cmd etc completions man docs; do
  [[ -d "$ROOT/$d" ]] && cp -R "$ROOT/$d" "$STAGE_DIR/"
done

# Copy semantic version and, when available, exact source revision metadata.
cp "$ROOT/VERSION" "$STAGE_DIR/VERSION"
BUILD_COMMIT_VALUE="${SSC_BUILD_COMMIT:-}"
if [[ -z "$BUILD_COMMIT_VALUE" && -f "$ROOT/BUILD_COMMIT" ]]; then
  BUILD_COMMIT_VALUE="$(tr -d '[:space:]' <"$ROOT/BUILD_COMMIT")"
fi
if [[ -z "$BUILD_COMMIT_VALUE" && -d "$ROOT/.git" ]] && command -v git >/dev/null 2>&1; then
  if [[ -z "$(git -C "$ROOT" status --porcelain 2>/dev/null || true)" ]]; then
    BUILD_COMMIT_VALUE="$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || true)"
  fi
fi
if [[ -n "$BUILD_COMMIT_VALUE" ]]; then
  [[ "$BUILD_COMMIT_VALUE" =~ ^[0-9a-f]{40}$ ]] || {
    echo "Invalid SSC_BUILD_COMMIT: expected a full 40-character commit SHA." >&2
    exit 2
  }
  printf '%s\n' "$BUILD_COMMIT_VALUE" >"$STAGE_DIR/BUILD_COMMIT"
fi

[[ -f "$STAGE_DIR/VERSION" && -f "$STAGE_DIR/lib/selfupdate.sh" && -f "$STAGE_DIR/cmd/ssc/ssc.sh" ]] || {
  echo "Staged installation is missing required files." >&2
  exit 1
}

# ---------- Atomically replace the shared tree ----------
if [[ -e "$SHARE_DIR" ]]; then
  BACKUP_DIR="$(mktemp -d "$SHARE_PARENT/.smartslurmcommands.old.XXXXXX")"
  rmdir "$BACKUP_DIR"
  mv "$SHARE_DIR" "$BACKUP_DIR"
fi
mv "$STAGE_DIR" "$SHARE_DIR"
STAGE_DIR=""
SHARE_SWAPPED=true

# Also copy man pages into per-user man dir for 'man' to find
if [[ -d "$ROOT/man" ]]; then
  echo "==> Installing man pages to $MAN_DIR"
  find "$ROOT/man" -type f -name '*.1' -exec install -m 0644 {} "$MAN_DIR/" \;
fi

# ---------- Install shims into BIN_DIR ----------
echo "==> Installing command shims to $BIN_DIR"
if [[ -d "$ROOT/bin" ]]; then
  for src in "$ROOT"/bin/*; do
    [[ -f "$src" && -x "$src" ]] || continue
    name="$(basename "$src")"
    cat > "$BIN_DIR/$name" <<EOF
#!/usr/bin/env bash
# Installed shim for $name (generated by install.sh)
set -Eeuo pipefail
SSC_HOME="$SHARE_DIR"
exec bash "\$SSC_HOME/cmd/$name/$name.sh" "\$@"
EOF
chmod 0755 "$BIN_DIR/$name"
    echo "  -> $BIN_DIR/$name"
  done
fi

echo
echo "==> Done."

# ---------- Helpful hints ----------
NEED_PATH_HINT=false
case ":${PATH}:" in
  *":${BIN_DIR}:"*) : ;;
  *) NEED_PATH_HINT=true ;;
esac

NEED_MANPATH_HINT=false
# Many systems respect $MANPATH only if set explicitly
if command -v man >/dev/null 2>&1; then
  if ! man -w 2>/dev/null | tr ':' '\n' | grep -q "^${PREFIX}/share/man\$"; then
    NEED_MANPATH_HINT=true
  fi
fi
# remove below both lines, once you have man configured.
NEED_MANPATH_HINT=false

if $NEED_PATH_HINT; then
  cat <<SNIP

Add ~/.local/bin to your PATH (recommended):
  echo 'export PATH="\$HOME/.local/bin:\$PATH"' >> ~/.bashrc
  source ~/.bashrc
SNIP
fi

# Bash completion hint (optional, Bash-only)
if [[ -f "$SHARE_DIR/completions/smartcancel.bash" ]]; then
  cat <<'SNIP'

Enable Bash completion (current shell):
  source "${HOME}/.local/share/smartslurmcommands/completions/smartcancel.bash"

Persist completion (append to ~/.bashrc):
  if [ -f "${HOME}/.local/share/smartslurmcommands/completions/smartcancel.bash" ]; then
    source "${HOME}/.local/share/smartslurmcommands/completions/smartcancel.bash"
  fi
SNIP
fi

if $NEED_MANPATH_HINT; then
  cat <<SNIP

Make per-user man pages discoverable (optional):
  echo 'export MANPATH="${PREFIX}/share/man:${MANPATH:-}"' >> ~/.bashrc
  source ~/.bashrc

Then you can run:
  man smartcancel
SNIP
fi

# ---------- Quick smoke tests (non-fatal) ----------
echo
if [[ -x "$BIN_DIR/mqpwd" ]]; then
  echo "==> Smoke test: $BIN_DIR/mqpwd (no args)"
  "$BIN_DIR/mqpwd" >/dev/null 2>&1 || true
fi
if [[ -x "$BIN_DIR/smartcancel" ]]; then
  echo "==> Smoke test: $BIN_DIR/smartcancel --help"
  "$BIN_DIR/smartcancel" --help >/dev/null 2>&1 || true
fi

echo "Installation complete into $PREFIX."

INSTALL_COMPLETE=true
if [[ -n "$BACKUP_DIR" && -d "$BACKUP_DIR" ]]; then
  rm -rf -- "$BACKUP_DIR"
fi
trap - EXIT
